update public.stock_items as item
set
  unit = catalog.unit,
  category = catalog.category,
  low_stock_threshold = 0,
  is_active = true,
  updated_at = now()
from stock_catalog_seed as catalog
where lower(trim(item.name)) = lower(trim(catalog.name));

insert into public.stock_items (name, unit, category, low_stock_threshold, is_active)
select catalog.name, catalog.unit, catalog.category, 0, true
from stock_catalog_seed as catalog
where not exists (
  select 1
  from public.stock_items as item
  where lower(trim(item.name)) = lower(trim(catalog.name))
);

delete from public.stock_movements as movement
using public.stock_items as item, stock_catalog_seed as catalog
where movement.item_id = item.id
  and lower(trim(item.name)) = lower(trim(catalog.name));

